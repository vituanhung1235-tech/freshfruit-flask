def adapt_postgres_sql(query):
    query = query.strip()
    ignore_insert = bool(
        re.match(r'^INSERT\s+OR\s+IGNORE\s+INTO\b', query, re.IGNORECASE)
    )
    if ignore_insert:
        query = re.sub(
            r'^INSERT\s+OR\s+IGNORE\s+INTO\b',
            'INSERT INTO',
            query,
            count=1,
            flags=re.IGNORECASE,
        )
        if not re.search(r'\bON\s+CONFLICT\b', query, re.IGNORECASE):
            query += ' ON CONFLICT DO NOTHING'

    match = re.match(
        r'^INSERT\s+INTO\s+([a-z_]+)\b',
        query,
        re.IGNORECASE,
    )
    if (
        match
        and match.group(1).lower() in ID_TABLES
        and not re.search(r'\bRETURNING\b', query, re.IGNORECASE)
    ):
        query += ' RETURNING id'

    return query.replace('?', '%s')


class HybridRow(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def _hybrid_row_factory(cursor):
    def make_row(values):
        columns = [column.name for column in cursor.description]
        return HybridRow(zip(columns, values))

    return make_row


class PostgresCursor:
    def __init__(self, cursor, returned_row=None, has_returning_id=False):
        self._cursor = cursor
        self._lastrowid_checked = has_returning_id
        self._lastrow = returned_row

    @property
    def lastrowid(self):
        if not self._lastrowid_checked:
            self._lastrow = self._cursor.fetchone()
            self._lastrowid_checked = True
        return self._lastrow['id'] if self._lastrow else None

    def fetchone(self):
        if self._lastrow is not None:
            row, self._lastrow = self._lastrow, None
            return row
        if self._lastrowid_checked:
            return None
        return self._cursor.fetchone()

    def fetchall(self):
        rows = []
        if self._lastrow is not None:
            rows.append(self._lastrow)
            self._lastrow = None
        if not self._lastrowid_checked:
            rows.extend(self._cursor.fetchall())
        return rows


class PostgresConnection:
    def __init__(self, connection):
        self._connection = connection

    def execute(self, query, parameters=()):
        adapted_query = adapt_postgres_sql(query)
        cursor = self._connection.execute(
            adapted_query,
            parameters,
        )
        has_returning_id = bool(
            re.search(r'\bRETURNING\s+id\s*$', adapted_query, re.IGNORECASE)
        )
        returned_row = cursor.fetchone() if has_returning_id else None
        return PostgresCursor(cursor, returned_row, has_returning_id)

    def executemany(self, query, parameter_rows):
        cursor = self._connection.cursor()
        cursor.executemany(
            adapt_postgres_sql(query),
            parameter_rows,
        )
        return PostgresCursor(cursor)

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()

    def close(self):
        self._connection.close()


def connect_postgres(database_url):
    if psycopg is None:
        raise RuntimeError(
            'PostgreSQL support requires psycopg. Install dependencies from requirements.txt.'
        )
    normalized_url = database_url.replace('postgres://', 'postgresql://', 1)
    return PostgresConnection(
        psycopg.connect(
            normalized_url,
            connect_timeout=10,
            row_factory=_hybrid_row_factory,
        )
    )


def initialize_postgres_schema(connection):
    for statement in POSTGRES_SCHEMA:
        connection.execute(statement)
    connection.execute("ALTER TABLE products ADD COLUMN IF NOT EXISTS image TEXT DEFAULT ''")


def sqlite_table_is_empty(database_path, table_name):
    connection = sqlite3.connect(database_path)
    try:
        return connection.execute(
            f'SELECT 1 FROM "{table_name}" LIMIT 1'
        ).fetchone() is None
    finally:
        connection.close()


def sqlite_database_path(root, configured_path):
    path = Path(configured_path)
    if not path.is_absolute():
        path = Path(root) / path
    return path
